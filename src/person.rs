/// Days a person can go hungry before it kills them.
///
/// Real starvation takes weeks — about forty days without food, far less
/// without water. What bites long before death is the weakness: a hungry
/// person works badly and cannot take heavy work at all.
const DAYS_TO_STARVE: f64 = 45.0;

/// What one person eats a day, from the same real figure the markets use:
/// 0.40 t of processed food a year.
pub const FOOD_PER_DAY: f64 = 0.40 / 365.0;

/// **What somebody does for a living.**
///
/// Thirteen trades that were really industries wearing a job's name — a
/// labourer was whoever worked at a works — until they became the
/// occupations `occupation.rs` reads from the published staffing of every
/// industry. The name stays because a person *has a trade*; what it is now
/// is an occupation, whoever employs them.
pub use crate::occupation::Occupation as Trade;

/// **What kind of hold somebody has on their work.**
///
/// Everything here was offered a shift at a time, which is how *casual*
/// work is done and is not how most people work. Most people have a
/// contract: guaranteed hours, paid whether or not trade was brisk, ended
/// by notice rather than by nobody ringing.
///
/// Real UK shares — **56% are permanent full-time and 44% are not**;
/// part-time is 24% (against an EU average of 17%); and zero-hours is
/// 2.9% of employment, about 900,000 people.
///
/// The distribution is wildly uneven by trade, and that unevenness is the
/// point: **28.8% of the accommodation and food workforce are on
/// zero-hours contracts against 2.1% in public administration.** A
/// fourteenfold difference in whether you know you have work next week.
#[derive(Copy, Clone, PartialEq, Eq, Debug)]
pub enum Employment {
    /// **A contract with guaranteed hours.** Paid on the contracted days
    /// whether or not there was work to do, and ended by notice or
    /// redundancy — not by the absence of a shift.
    FullTime,
    /// The same security, fewer days. A quarter of British employees.
    PartTime,
    /// **No guaranteed hours**: work is offered shift by shift and
    /// declined the same way. This is what everybody here was, and it is
    /// what 3% of people actually are.
    Casual,
    /// Working on your own account. About 13% of the workforce, and the
    /// one way out of a town with no work in it.
    SelfEmployed,
    /// **Work that only exists for part of the year.**
    ///
    /// Farming and fishing, chiefly. Real agricultural labour swings about
    /// twofold between season and slack, and Britain brings in some 45,000
    /// people a year on a seasonal visa purely to get the harvest in.
    /// Fishing adds weather to the same shape: 30-50% of winter days in
    /// the North Sea are lost to it outright.
    ///
    /// The consequence is a **year with a shape to it**: earn hard for
    /// three months and make it last nine, or move. A wage that is
    /// perfectly adequate in August is nothing at all in February, and
    /// that is not unemployment — it is the job.
    Seasonal,
    /// Not working.
    None,
}

impl Employment {
    pub fn name(self) -> &'static str {
        match self {
            Employment::FullTime => "full-time",
            Employment::PartTime => "part-time",
            Employment::Casual => "casual",
            Employment::SelfEmployed => "self-employed",
            Employment::Seasonal => "seasonal",
            Employment::None => "out of work",
        }
    }

    /// **Days a week the contract guarantees.** Real full-time is five;
    /// British part-timers average two and a half to three.
    pub fn contracted_days_a_week(self) -> f64 {
        match self {
            Employment::FullTime => 5.0,
            Employment::PartTime => 2.75,
            _ => 0.0,
        }
    }

    /// Whether they are paid without having to find the work first.
    pub fn is_contracted(self) -> bool {
        matches!(self, Employment::FullTime | Employment::PartTime)
    }

    /// **How much work there is, given where the year is.**
    ///
    /// One for everybody whose work does not care about the season, and
    /// for a seasonal hand it follows the harvest — which peaks over about
    /// six weeks and falls away to a fraction of that. Real agricultural
    /// employment swings about twofold; the ground still wants ploughing
    /// and tending out of season, so the floor is well above nil.
    pub fn in_season(self, harvest: f64) -> f64 {
        match self {
            Employment::Seasonal => (0.35 + 0.90 * harvest).clamp(0.0, 1.0),
            _ => 1.0,
        }
    }
}

/// **Which days of the week this trade works.**
///
/// A year of 365 days was being lived as 365 identical ones, and real
/// working life is shaped by the week far more sharply than by the season.
///
/// - An **office** and **public administration** keep Monday to Friday.
///   That is what those jobs *are*, and it is most of why people want them.
/// - A **shop** or a **kitchen** is open seven days and is busiest at the
///   weekend — real retail footfall peaks on Saturday at about 1.5 times a
///   weekday.
/// - A **works**, a **hospital**, a **power station** run rotas that do
///   not care what day it is.
/// - A **farm** does not care either. Animals do not observe Sunday.
///
/// Which is why part-timers and students work weekends: not by accident,
/// but because that is when the trade is and when the full-timers will
/// not.
pub fn works_on(trade: Trade, day: u64, employment: Employment) -> f64 {
    use crate::econ::Weekday;
    use crate::occupation::Week;
    let wd = Weekday::on(day);
    match trade.week() {
        // Monday to Friday, and that is the whole of it.
        Week::Weekdays => {
            if wd.is_weekend() {
                0.0
            } else {
                1.0
            }
        }
        // Mostly weekdays, with a share of the weekend covered.
        Week::MostlyWeekdays => {
            if wd.is_weekend() {
                0.35
            } else {
                1.0
            }
        }
        // **A hospital does not close on Sunday**, and nor does a police
        // station or a garrison: the rota runs through the weekend, the
        // nights and Christmas.
        Week::EveryDay => 1.0,
        // A site keeps weekday hours; an emergency call-out does not, and
        // that is where a fair part of the trade's money comes from.
        Week::SiteWithCallOuts => {
            if wd.is_weekend() {
                0.30
            } else {
                1.0
            }
        }
        // **Open seven days, busiest at the weekend** — and the weekend
        // shifts are covered by the people who are not on a full-time
        // contract, because the full-timers have Monday to Friday and
        // somebody has to be on the till on Saturday.
        Week::OpenSevenDays => {
            let trade_today = wd.retail_trade();
            match employment {
                Employment::FullTime => {
                    if wd.is_weekend() {
                        0.35
                    } else {
                        trade_today
                    }
                }
                // **This is why student and part-time work is weekend
                // work.** It is not a preference, it is where the shifts
                // that are going actually are.
                _ => {
                    if wd.is_weekend() {
                        trade_today * 1.6
                    } else {
                        trade_today * 0.7
                    }
                }
            }
        }
        // Rotas, and a herd does not observe Sunday.
        Week::Rota => {
            if wd == Weekday::Sunday {
                0.55
            } else {
                1.0
            }
        }
    }
}

/// **How a trade is actually employed**, from the real industry figures.
///
/// Returns the chance of full-time, part-time and casual in that order.
/// Retail and hospitality carry the insecurity; public administration
/// carries almost none of it.
pub fn employment_mix(trade: Trade) -> (f64, f64, f64) {
    trade.employment_mix()
}

impl Person {
    /// What level they are at, 0-10.
    pub fn level(&self, skill: Skill) -> u8 {
        Skill::level_from_days(self.practice[skill as usize])
    }

    /// The level in the work they do for a living.
    pub fn competence(&self) -> u8 {
        self.level(self.trade.skill())
    }

    /// **What they are worth against the going rate**, from how good they
    /// actually are at the work.
    pub fn worth(&self) -> f64 {
        skill_premium(self.competence(), self.trade.wants_level())
    }

    /// **Whether they may be taken on at the work.**
    ///
    /// The qualification the work asks for, or — for management alone — the
    /// experience that stands in for it. Most shop, kitchen and site
    /// managers come to it through running a crew rather than a degree: the
    /// BLS gives food service managers a high school diploma and a few
    /// years' experience as the usual way in. So somebody whose practice at
    /// running things has reached what a manager's post wants is qualified
    /// for one. Running a crew builds it at half a day's practice a day,
    /// which reaches that level in about seven hundred working days.
    pub fn qualified_for(&self, trade: Trade) -> bool {
        self.qualification >= qualification_for(trade)
            || (trade.skill() == Skill::Management
                && self.level(Skill::Management) >= trade.wants_level())
    }

    /// **How well they actually do the work**, nought to one — which is not
    /// what anybody thinks of them.
    ///
    /// What they put into it and whether they can do what it asks: effort
    /// and skill against the level the work wants, in equal parts. For a
    /// supervisor, the skill that counts is running the crew, which a year of
    /// doing it takes to level three — so somebody made up for being the best
    /// at the work and no good at running it shows as such, which is the
    /// Peter Principle *(Benson, Li and Shue, 2019: across 131 firms, the
    /// best salespeople were the ones promoted and made worse managers)*.
    /// And nobody does their best work hungry or ill. Designed weights.
    pub fn performance(&self) -> f64 {
        /// The level of running things a supervisor's post asks for:
        /// designed, at about a year of doing it.
        const RUNNING_A_CREW_WANTS: u8 = 3;
        let (skill, wanted) = match self.rank {
            Rank::Hand => (self.competence(), self.trade.wants_level()),
            Rank::Supervisor => (self.level(Skill::Management), RUNNING_A_CREW_WANTS),
        };
        let fit = (0.5 + 0.1 * (skill as f64 - wanted as f64)).clamp(0.0, 1.0);
        (0.5 * self.diligence + 0.5 * fit) * (0.6 + 0.4 * self.condition.clamp(0.0, 1.0))
    }

    /// **What running a crew adds to the pay**, as a multiple of the work's
    /// own rate: what the published supervisors of that work earn over its
    /// median, which runs from a quarter more in a kitchen to seven tenths
    /// in police and security. One for one of the crew.
    pub fn rank_premium(&self) -> f64 {
        match self.rank {
            Rank::Hand => 1.0,
            Rank::Supervisor => {
                let own = self.trade.days_of_food_a_day();
                if own > 0.0 {
                    (self.trade.supervisor_days_of_food_a_day() / own).max(1.0)
                } else {
                    1.0
                }
            }
        }
    }

    /// **The ceiling on what somebody can become.**
    ///
    /// Aptitude is what they can learn — the same axis that decides
    /// whether a course is out of reach — so it decides where practice
    /// stops paying. Most people top out competent to skilled at their
    /// work, which is the honest shape of it: **legendary is rare because
    /// the ability to get there is rare**, not because the hours are
    /// unavailable.
    pub fn ceiling(&self) -> u8 {
        // **Most people top out competent to skilled at their work.**
        // Set at 4 to 10 the average person came out a master of their
        // trade, which flatters everybody: the point of a ceiling is that
        // it is usually low enough to matter.
        (2.0 + self.aptitude * 6.0).round().clamp(1.0, 10.0) as u8
    }

    /// **Put somebody into a trade, with the experience that implies.**
    ///
    /// One definition, because the rule was written out twice in
    /// `populace.rs` and a third copy had appeared in a test — which is
    /// how the first copy comes to be missing. Its own comment records
    /// what happens when the order goes wrong: *assigning the years first
    /// put them against the skill of a trade the person then did not end
    /// up in, and 44% of a country came out untrained at everything.*
    ///
    /// **Experience is what somebody has actually done**, so it follows
    /// the trade rather than preceding it: years available since leaving
    /// education, at about 220 working days each, capped by what their
    /// aptitude lets them reach. Somebody genuinely changing trade in
    /// middle life is a different thing and should keep their old
    /// practice and start the new one near nothing — this is for settling
    /// a person into the trade they have been in.
    pub fn settle_into(&mut self, trade: Trade) {
        self.trade = trade;
        let years_in = (self.age_years - 18.0 - self.qualification.years_to_earn()).max(0.0);
        let cap = Skill::days_to_reach(self.ceiling());
        self.practice[trade.skill() as usize] = (years_in * 220.0).min(cap);
    }

    /// **A day of doing the work.**
    ///
    /// Practice accrues at the trade's own skill, faster for somebody who
    /// is good at their job, and stops counting once they have reached
    /// what they are capable of. DF and CDDA both let use raise a skill
    /// and disuse lower it; this does the same, slowly, because a trade
    /// you have not worked for years is a trade you are rusty at rather
    /// than one you have forgotten.
    pub fn practise(&mut self, worked: bool) {
        let here = self.trade.skill() as usize;
        if worked && self.level(self.trade.skill()) < self.ceiling() {
            // Somebody diligent gets more out of the same day.
            self.practice[here] += 0.6 + 0.8 * self.diligence;
        }
        // **Running a crew is practice at running things**, alongside the
        // work itself — which is what a supervisor brings to a manager's
        // post. Half a day's worth, because most of the day is still the
        // work: designed.
        let running = Skill::Management as usize;
        let supervising = worked && self.rank == Rank::Supervisor && running != here;
        if supervising && self.level(Skill::Management) < self.ceiling() {
            self.practice[running] += (0.6 + 0.8 * self.diligence) * 0.5;
        }
        // **Everything else fades.** Real skill decay is slow — a trade
        // is still there years later, just rusty — so this is set so that
        // a decade away costs a couple of levels rather than all of them.
        for i in 0..self.practice.len() {
            if (i == running && supervising) || (i == here && worked) {
                continue;
            }
            self.practice[i] = (self.practice[i] - 0.06).max(0.0);
        }
    }
}

/// Work somebody wants done, posted because the economy wants it done.
#[derive(Clone, Debug)]
pub struct Contract {
    pub kind: Job,
    /// Day it appeared, and the day after which nobody wants it any more.
    pub posted: u64,
    pub expires: u64,
    /// What it pays, in full, on completion.
    pub pay: f64,
    /// Days of work it takes.
    pub days: f64,
    pub trade: Trade,
}

#[derive(Clone, Debug)]
pub enum Job {
    /// **A day driving for a carrier.**
    ///
    /// The difference between this and `Haul` is the difference between a
    /// job and a gig. A haul is a load somebody happened to want shifted
    /// today; this is a firm with a fleet, a depot and a rota, and it is
    /// where most real driving work actually is — road haulage is an
    /// industry of operators, not of men with lorries waiting for a
    /// cargo to turn up.
    ///
    /// The goods have already moved: `logistics.rs` shipped them through
    /// the journal this morning. This is the wage for having driven.
    Driving { carrier: usize, km: f64 },
    /// Move somebody else's goods along a route for a wage. The margin is
    /// theirs; the driver is paid by the day, and ends up at the far end.
    Haul {
        route: usize,
        commodity: Commodity,
        tonnes: f64,
        from_market: usize,
        to_market: usize,
    },
    /// **Buy the cargo yourself.**
    ///
    /// The same journey, but on your own account: you pay for the goods at
    /// this end and sell at the other, so the margin is yours and so is
    /// the risk. It needs capital, which is what a wage is for, and the
    /// price can move against you while you are on the road — which is
    /// what makes it a decision rather than a better wage.
    Venture {
        route: usize,
        commodity: Commodity,
        tonnes: f64,
        from_market: usize,
        to_market: usize,
        /// What the load cost, paid on setting out. Refundable in the sense
        /// that goods never loaded were never paid for.
        outlay: f64,
        /// Fodder, fuel and wear for the journey. Spent whether or not
        /// there turned out to be anything to carry, which is exactly what
        /// makes a wasted trip hurt.
        running: f64,
    },
    /// A shift at a works that has orders to fill.
    Shift { site: usize, market: usize },
    /// **A week in public service** — a school, a hospital, an office, a
    /// station. No site, because the state's work is not a stockpile with
    /// a door on it, and no cargo, because what it produces is a service.
    Public {
        market: usize,
        service: crate::state::Service,
    },
    /// A day in a private service — a building site, a kitchen, an office.
    Service {
        market: usize,
        sector: crate::services::Sector,
    },
    /// **A day at a carrier's depot** — dispatching, loading, keeping the
    /// fleet on the road — rather than behind the wheel.
    Depot { carrier: usize },
    /// A shift in a shop, at one of the jobs a shop actually contains.
    Counter {
        site: usize,
        market: usize,
        role: Fixture,
    },
}

impl Contract {
    pub fn describe(&self, econ: &Economy) -> String {
        match &self.kind {
            Job::Haul {
                commodity,
                tonnes,
                from_market,
                to_market,
                ..
            } => format!(
                "haul {tonnes:.0} t of {commodity} from {} to {} — {:.0} over {:.1} days",
                econ.markets[*from_market].name, econ.markets[*to_market].name, self.pay, self.days,
            ),
            Job::Venture {
                commodity,
                tonnes,
                from_market,
                to_market,
                outlay,
                ..
            } => {
                format!(
                    "bought {tonnes:.1} t of {commodity} for {outlay:.0} to sell in {} \
                 ({:.1} days on the road)",
                    econ.markets[*to_market].name, self.days,
                )
                .replace("  ", " ")
                    + &format!(" — from {}", econ.markets[*from_market].name)
            }
            Job::Counter { site, role, .. } => format!(
                "{} at {} — {:.0} for {:.1} days",
                match role {
                    Fixture::Till => "a shift on the registers",
                    Fixture::Shelving => "a shift stocking shelves",
                    Fixture::StockRack => "a shift in the backroom",
                    Fixture::LoadingBay => "a shift on receiving",
                    Fixture::Counter => "a shift at the deli counter",
                    Fixture::ChillCabinet => "a shift on the cold case",
                    Fixture::ColdStore => "a shift in the walk-in",
                },
                econ.ledger.sites[*site].name,
                self.pay,
                self.days,
            ),
            Job::Shift { site, market } if *site == usize::MAX => format!(
                "a day carting about {} — {:.0}",
                econ.markets[*market].name, self.pay,
            ),
            Job::Shift { site, .. } => format!(
                "a shift at {} as {} — {:.0} for {:.1} days",
                econ.ledger.sites[*site].name,
                self.trade.name(),
                self.pay,
                self.days,
            ),
            Job::Depot { carrier } => format!(
                "a day at {}'s depot as {} — {:.0}",
                econ.logistics
                    .as_ref()
                    .and_then(|l| l.carriers.get(*carrier))
                    .map(|c| c.name.as_str())
                    .unwrap_or("a carrier"),
                self.trade.name(),
                self.pay,
            ),
            Job::Driving { carrier, km } => format!(
                "a day on the road for {} — {:.0} km, {:.0}",
                econ.logistics
                    .as_ref()
                    .and_then(|l| l.carriers.get(*carrier))
                    .map(|c| c.name.as_str())
                    .unwrap_or("a carrier"),
                km,
                self.pay,
            ),
            Job::Service { market, sector } => format!(
                "a day in {} in {} — {:.0}",
                sector.name(),
                econ.markets[*market].name,
                self.pay,
            ),
            Job::Public { market, service } => format!(
                "a week in {} in {} — {:.0}",
                service.name(),
                econ.markets[*market].name,
                self.pay,
            ),
        }
    }

    /// Money that must be found before the work can be taken.
    ///
    /// The cargo *and* the journey. You need the fodder before you set off,
    /// not after you arrive — and charging the running cost against the
    /// profit while never taking it out of the purse handed him free
    /// diesel, which is the same money printer wearing a different hat.
    pub fn stake(&self) -> f64 {
        match &self.kind {
            Job::Venture {
                outlay, running, ..
            } => *outlay + *running,
            _ => 0.0,
        }
    }

    /// Pay per day of work, which is how anyone actually compares two jobs.
    pub fn daily_rate(&self) -> f64 {
        self.pay / self.days.max(0.01)
    }
}

/// **Where somebody sleeps.**
///
/// Housing is the largest thing a household spends money on — a quarter
/// to a third of income against a tenth to a seventh on food — and it was
/// not modelled at all, so everybody in this world lived rent-free.
///
/// It is also the thing that fails first and hurts longest. Rent is due
/// whether or not you were on the rota this week, and once you are out
/// you are much harder to employ, because the address goes on the form.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Housing {
    /// A room in somebody else's place. Cheap, and no security at all.
    Lodging,
    /// A tenancy of his own.
    Rented,
    /// Bought, and the rent stops.
    Owned,
    /// Nowhere.
    Homeless,
}

/// **Where somebody stands with whoever they rent from**, which is a
/// ladder rather than a switch.
///
/// Missing one payment does not put anybody out. What it does is start a
/// clock: a late fee, then a notice, then — if it is still not paid and
/// nothing is agreed — the end of the tenancy. Real American practice, and
/// the figures say the ladder matters far more than the last rung:
/// **6.1% of renter households were filed on in 2016 and 2.3% were put
/// out**, so about **38% of filings end in an eviction** *(Eviction Lab,
/// national estimates: 2,350,042 filings and 898,479 evictions against
/// 38.4M renter households)*. A model with no ladder cannot produce those
/// two numbers at once, because it only has the second one.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Tenancy {
    /// Paid up, or near enough that nobody has said anything.
    Current,
    /// Behind, and told so — the notice to pay or quit. `by` is the day
    /// the landlord expects to be paid by.
    UnderNotice { served: u64, by: u64 },
    /// The landlord agreed to wait, because they asked and had a record
    /// worth waiting for. `until` is what was agreed.
    Indulged { until: u64 },
    /// **Working it off.** The landlord took the work instead of the
    /// money, which is what a tenant who can actually do the job offers —
    /// and it has a legal form worth copying: **repair and deduct**, where
    /// a tenant puts right what the landlord will not and takes it off the
    /// rent, capped in most states at about a month's rent.
    WorkingItOff { until: u64 },
}

/// **What a month behind costs before anybody is put out**: five per cent
/// of a month's rent, which is the cap most American states put on a late
/// fee.
pub const LATE_FEE: f64 = 0.05;

/// **How long a month is**, for a bill that falls due once a month.
pub const A_MONTH: u64 = 30;

/// **How long a notice to pay or quit runs.** Real notices are three to
/// fourteen days and the court adds weeks on top; fourteen stands for
/// both, because what this model needs is that a notice is not an
/// eviction.
pub const NOTICE_DAYS: u64 = 14;

/// **How long a landlord waits when they agree to wait**, and how long a
/// stretch of work in lieu runs before it is settled up.
pub const INDULGENCE_DAYS: u64 = 30;

impl Housing {
    pub fn name(self) -> &'static str {
        match self {
            Housing::Lodging => "a rented room",
            Housing::Rented => "a place of his own",
            Housing::Owned => "his own front door",
            Housing::Homeless => "nowhere",
        }
    }

    /// What it costs a day, against the going rent for a tenancy.
    ///
    /// A room in a shared house is about half a flat; owning costs
    /// nothing further once it is bought, which is the whole reason
    /// people want to.
    pub fn share_of_rent(self) -> f64 {
        match self {
            Housing::Lodging => 0.5,
            Housing::Rented => 1.0,
            Housing::Owned => 0.0,
            Housing::Homeless => 0.0,
        }
    }
}

/// How a person is getting on.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum State {
    Idle,
    Working { until: u64 },
    Dead,
}

pub struct Person {
    pub name: String,
    pub trade: Trade,
    /// Which market they are in. The finest position anyone has yet.
    pub market: usize,
    pub money: f64,
    /// Days of food in hand.
    pub larder: f64,
    /// 0 (starving) to 1 (fed). Falls when there is nothing to eat.
    pub condition: f64,
    pub state: State,
    /// **What they can move goods with, and therefore what they can trade.**
    ///
    /// A wage haul is driving somebody else's lorry, so it does not depend
    /// on this. Trading on your own account entirely does: a man on foot
    /// carries 35 kg over the pass, not twenty-four tonnes, and the road
    /// out of that is to buy a better vehicle rather than to find a better
    /// price.
    pub conveyance: Conveyance,
    /// Where he sleeps, and what it costs him.
    pub housing: Housing,
    /// **What they are behind on the rent**, in money. Nobody is put out
    /// the day they come up short: it goes on the slate, and what happens
    /// next is [`Tenancy`].
    pub rent_owed: f64,
    /// **Where they stand with whoever they rent from.**
    pub tenancy: Tenancy,
    /// **The day the next month's rent falls due.** Rent is a monthly
    /// bill, the way the power is: it is not a daily drip, and the
    /// difference decides what being behind even means.
    pub rent_due_on: u64,
    /// **How many times they have been served notice, put out, and had a
    /// landlord take the work instead.** Counted so the ladder can be held
    /// against the real one: 6.1% of American renter households were filed
    /// on in 2016 and 2.3% put out *(Eviction Lab)*.
    pub notices: u32,
    pub evictions: u32,
    pub worked_off: u32,
    /// **What hold they have on their work.** Most people have a contract
    /// with guaranteed hours; this model gave everybody casual work.
    pub employment: Employment,
    /// **What they are qualified to do.** Anybody could be anything: a man
    /// off the street could be an engineer, and three years at a
    /// university bought nothing because nothing required it.
    pub qualification: Qualification,
    /// **How old they are.** The model had no ages at all, so there were
    /// no children, nobody retired, and nobody was replaced.
    ///
    /// Real: working age is 16-64, life expectancy about 81, and the mean
    /// age at a first birth is 29. A population is roughly 18% under 16,
    /// 64% working age and 19% over 65 — which is a dependency ratio of
    /// about 57 dependents to every 100 working.
    pub age_years: f64,
    /// **Children in the household, and how old.**
    ///
    /// They cost, and what they cost falls off a cliff when they start
    /// school: full-time nursery for an under-two is **65% of a median
    /// take-home wage in England**, and after-school care for a five to
    /// eleven year old is **17%**. That cliff is why maternal employment
    /// with under-fives is **just over 60%** against about 75% overall.
    /// Ages of dependent children still at home. They become people of
    /// their own at sixteen.
    pub children: Vec<f64>,
    /// **Who they are married to**, if anybody.
    ///
    /// The first thing in this model to hold another person's handle
    /// across a day, and the reason the handle had to become durable
    /// first: an index would have pointed at whoever moved into the slot.
    pub spouse: Option<Id<Person>>,
    /// **Who they came from.** Set when a child turns sixteen and becomes
    /// a person in their own right. Children are not stored the other way
    /// round — a cohort is small and scanning it on a death is cheaper
    /// than keeping two lists that can disagree.
    pub parents: Vec<Id<Person>>,
    /// **What share of a household's costs this person carries.**
    ///
    /// Everybody was living alone and paying a full rent, which is not how
    /// people live: the **average British household is 2.36 people**, 30%
    /// are one person, 27% a couple, 22% a couple with children, and about
    /// one private renter in five shares.
    ///
    /// And a household is cheaper per head than a person is. The measure
    /// is the **modified OECD equivalence scale** — the first adult counts
    /// 1.0, each further adult 0.5, each child 0.3 — because a second
    /// person does not double the rent, the heating or the cooking. A
    /// two-bed is not twice a one-bed.
    ///
    /// So a couple needs 1.5 times a single person's income rather than
    /// twice it, and each of them carries 0.75 of a full cost. **That 25%
    /// is a large part of why people move in together**, and it is the
    /// difference between a part-time retail wage keeping a roof and not.
    pub household_share: f64,
    /// Days he has been sleeping out.
    pub days_homeless: u64,
    /// The contract in hand, if any.
    pub job: Option<Contract>,
    /// **How good they actually are at it**, 0 to 1. Fixed; this is the
    /// person, not their reputation.
    pub diligence: f64,
    /// **What they can learn**, 0 to 1 — which is not the same as how hard
    /// they work at it, and not everybody can do everything.
    ///
    /// Roughly normally distributed, as ability is: most people are
    /// middling and the very able and the very not are rare. Real
    /// cognitive ability correlates with educational attainment at about
    /// **r = 0.5** — strong enough that it plainly matters, far too weak
    /// to be the whole story.
    ///
    /// **Background matters comparably.** Feinstein's work on the 1970
    /// British Cohort found children from deprived backgrounds who scored
    /// well at 22 months were on average overtaken by higher-SES children
    /// before primary school — though later research has challenged the
    /// strong form of that crossover, so the model takes the defensible
    /// version: **ability and money each gate the same door, and neither
    /// alone opens it.**
    pub aptitude: f64,
    /// **Days of practice at each skill.** Levels are read off this rather
    /// than stored, the way experience works in both references.
    pub practice: [f64; N_SKILLS],
    /// **How they are regarded**, 0 to 1 — which is a different thing.
    ///
    /// Promotion does not run on days worked. It runs on what the people
    /// who decide believe about you, and that belief is a **noisy read of
    /// the work plus everything else**: who saw it, who says so, how long
    /// you have been about. Real performance ratings correlate with real
    /// performance at something like 0.3-0.5 — good enough that being good
    /// helps, far too weak to be the only thing that matters.
    ///
    /// Which is why two people with identical days worked get different
    /// lives. Gated on tenure alone they got the same one.
    pub standing: f64,
    /// **How much the people who decide have actually seen of you**, 0 to
    /// 1.
    ///
    /// The single strongest finding in the research on this: in **73% of
    /// promotions the person had worked with the hiring manager or the
    /// hiring manager's boss**. Proximity to whoever decides beats being
    /// good at it, and managers are known to suppress the visibility of
    /// people they do not want to lose.
    ///
    /// It has a real consequence here: a haulier is away and a shop worker
    /// is in front of the manager every shift, so the same ability gets
    /// noticed in one and not the other. Being good somewhere nobody
    /// watches is worth very little.
    pub visibility: f64,
    /// What has happened to them. The beginning of B4's memory log.
    pub log: Vec<String>,
    pub days_hungry: u64,
    /// Days since he last had work. What actually drives someone to move.
    pub days_idle: u64,
    pub days_worked: u64,
    /// Days spent carrying his own cargo. What decides whether a vehicle
    /// is worth its keep — one that earns on twelve days a year and eats
    /// on three hundred and sixty-five is a way to go broke slowly.
    pub days_trading: u64,
    /// **Days a load was there to be carried, whether or not he could.**
    ///
    /// What decides whether a vehicle is worth its keep is how often it
    /// would be *used*, and judging that by what he has already done is
    /// circular: he cannot trade without a vehicle, so his record says
    /// never, so he never buys one. A man sat on seven thousand days of
    /// food doing casual day work for five a time because of it.
    pub days_offered: u64,
    /// Gross takings: wages, and the profit on ventures after their costs.
    pub earned: f64,
    /// Everything that went out and did not come back — food eaten, and
    /// the vehicles bought. With these two, `money` reconciles exactly to
    /// what he started with, which is the nearest thing to a money ledger
    /// a person has yet.
    pub spent: f64,
    /// **Who they are**, as against what they do for a living.
    ///
    /// Until this existed there was **no whole person in this
    /// simulation**. There were two halves that shared an `Id<Person>` by
    /// convention and nothing else: this type, which has a trade, a wage,
    /// a house and a skill, and `mind::Mind`, which has a personality,
    /// values, concerns and needs and which *nothing owned* —
    /// `Mind::draw` was called by tests and one diagnostic binary, and
    /// `populace.rs`, `labour.rs` and `game.rs` mentioned it nowhere.
    ///
    /// `converse::ask` takes `Id<Person>` handles for speaker and listener
    /// **and** a `&Mind` as a separate argument, so the two being the same
    /// individual was a caller's promise rather than a type. Which meant
    /// the person you could walk up to and talk to did not exist: the one
    /// with a job and a house had no values, no memory and no
    /// relationships, and the one that could be lied to was employed by
    /// nobody and paid by nobody.
    ///
    /// **Drawn from the name**, like `diligence`, so the same world
    /// rebuilds the same people — and against a *neutral* culture,
    /// because nothing in this model yet derives a town's values.
    /// `custom.rs` derives its **norms** from the ground and says outright
    /// that it is deliberately mundane and that grand moral questions
    /// belong to `mind::Value`; no equivalent exists for those. A caller
    /// that has a real culture redraws. That is the same honesty as
    /// `aptitude` being middling until somebody has a distribution.
    pub mind: crate::mind::Mind,
    /// **What they have seen and been told**, and how they came by it.
    ///
    /// The other half of being somebody you can talk to. A person with
    /// convictions and no memory cannot answer "how was your day" — and
    /// `converse.rs` is built entirely around searching *their* traces,
    /// so that a man who was not there cannot be made to know. Until this
    /// sat on the person, the caller supplied the memory and the promise
    /// that it was his.
    pub memory: crate::memory::Memory,
    /// **What they make of other people**, one record per person they
    /// have met, held in their own head and nobody else's.
    ///
    /// Directed on purpose: Alice's record of Bob and Bob's of Alice are
    /// two things that need not agree, which is what `relations.rs`
    /// exists to say. Empty at birth, because a relationship is something
    /// that happens rather than something you are issued with — and
    /// keyed by `Id<Person>`, which outlives the person, since you go on
    /// owing, fearing and loving the dead.
    ///
    /// A `BTreeMap` rather than a hash: this project's save format
    /// requires that identical state gives identical bytes, and a
    /// `HashMap` anywhere in it would break that.
    pub relations:
        std::collections::BTreeMap<crate::id::Id<Person>, crate::relations::Relationship>,
    /// **What they are trying to do about earning a living**, what they
    /// have heard that bears on it, and whether anything has given them a
    /// reason to think again. Spec A4; see `planner.rs`.
    ///
    /// The same type the player will have. Nothing in it is told what the
    /// world holds: it learns of openings by being told, and it decides
    /// only when one of A4.5's four triggers says to.
    pub planner: crate::planner::Planner,
    /// **Days worked at the trade they are in now**, as against in their
    /// life. The same figure as `days_worked` for anybody who has never
    /// changed trade; for somebody who has, it is what a new employer has
    /// seen of them — which is what probation and promotion are judged on.
    pub days_at_trade: u64,
    /// **Whether they run a crew of the work they do**, or are one of it.
    /// A step up inside the trade, not a trade of its own: see [`Rank`].
    pub rank: Rank,
    /// **The day their work was last reviewed**, or they last started in a
    /// post — a year on from either, they are reviewed again.
    pub reviewed_on: u64,
    /// **What the last review said**, which is what the next one is read
    /// against: a warning stands until a review clears it, and a
    /// commendation until the next review.
    pub review: Review,
}

/// **What a review came to.**
#[derive(Copy, Clone, PartialEq, Eq, Debug)]
pub enum Review {
    /// Doing the job.
    Sound,
    /// Well above what the work asks: considered for a post a year early.
    Commended,
    /// Below it, and told so. A second such review has a consequence.
    Warned,
}

/// **Where somebody stands in the crew they work in.**
///
/// A supervisor was an occupation of its own, drawn from no staffing
/// pattern and promoted into from anywhere — while every published group
/// already counts its own first-line supervisors inside it. So the sample
/// came out a fifth supervisors against a real twentieth: a cook made up
/// was counted once as a cook's post and again as a supervisor's, and
/// teachers and nurses were promoted into a rung their work does not have.
///
/// A supervisor is now a cook who runs the kitchen, still in food service
/// and still practising it, paid what the published supervisors of that
/// work are paid. How many there are is the crew: `Occupation::crew`.
/// Management above them is an occupation, because it is different work.
#[derive(Copy, Clone, PartialEq, Eq, Debug)]
pub enum Rank {
    /// One of the crew.
    Hand,
    /// Runs a crew of the work.
    Supervisor,
}

impl Person {
    pub fn new(name: impl Into<String>, trade: Trade, market: usize, money: f64) -> Self {
        let name: String = name.into();
        let name_for_traits = name.as_str();
        let diligence = hash_unit(name_for_traits, 0xD1_11_6E_CE);
        Person {
            name: name.clone(),
            trade,
            market,
            money,
            larder: 3.0,
            condition: 1.0,
            state: State::Idle,
            conveyance: Conveyance::OnFoot,
            // Everybody starts in a rented room. Nobody arrives owning
            // anything, and this is the cheapest roof there is.
            housing: Housing::Lodging,
            rent_owed: 0.0,
            tenancy: Tenancy::Current,
            rent_due_on: 0,
            notices: 0,
            evictions: 0,
            worked_off: 0,
            // Nobody arrives with a contract. One is something you get.
            employment: Employment::None,
            // Alone until somebody says otherwise.
            household_share: 1.0,
            // **Qualified for the trade they are.** Nobody creates an
            // unlicensed lorry driver — the licence is what makes them one.
            // A caller modelling somebody's *route* into a trade sets this
            // themselves and starts them lower.
            qualification: qualification_for(trade),
            // Grown, and nobody's parent, until somebody says otherwise.
            age_years: 30.0,
            children: Vec::new(),
            spouse: None,
            parents: Vec::new(),
            days_homeless: 0,
            job: None,
            // **Ability varies from person to person**, and it has to be
            // stable and rebuildable from a seed, so it comes off the
            // name. A caller with a real distribution to draw from can
            // overwrite it.
            diligence,
            // Middling until a caller draws from a real distribution.
            aptitude: 0.5,
            // **The same name gives the same person**, which is the rule
            // `diligence` above already keeps and what makes a world
            // rebuildable. A neutral culture, because no town yet has
            // values of its own for somebody to depart from.
            mind: crate::mind::Mind::draw(
                &mut crate::rng::Rng::new(hash_seed(name_for_traits, 0xB12D_5EED_0001)),
                &[],
            ),
            // **Nobody is born remembering anything**, and nobody is born
            // knowing anybody. Both fill up by living.
            memory: crate::memory::Memory::new(),
            relations: Default::default(),
            planner: crate::planner::Planner::new(),
            days_at_trade: 0,
            rank: Rank::Hand,
            reviewed_on: 0,
            review: Review::Sound,
            practice: [0.0; N_SKILLS],
            standing: 0.5,
            visibility: 0.0,
            log: Vec::new(),
            days_hungry: 0,
            days_idle: 0,
            days_worked: 0,
            days_trading: 0,
            days_offered: 0,
            earned: 0.0,
            spent: 0.0,
        }
    }

    pub fn alive(&self) -> bool {
        self.state != State::Dead
    }

    pub fn note(&mut self, day: u64, what: impl Into<String>) {
        self.log.push(format!("day {day}: {}", what.into()));
    }
}

