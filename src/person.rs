/// Live one day: eat, work if working, look for work if not.
///
/// Order matters and is the order a day happens in. You eat before you
/// decide anything, because hunger is what decides it.
/// A deterministic 0..1 from a name and a number. Reputation must rebuild
/// identically from a seed like everything else.
fn hash_unit(name: &str, salt: u64) -> f64 {
    let mut h = salt ^ 0xA076_1D64_78BD_642F;
    for b in name.as_bytes() {
        h = (h ^ *b as u64).wrapping_mul(0x1000_0000_01B3);
    }
    h ^= h >> 33;
    h = h.wrapping_mul(0xFF51_AFD7_ED55_8CCD);
    h ^= h >> 33;
    (h >> 11) as f64 / (1u64 << 53) as f64
}

pub fn live_a_day(person: &mut Person, econ: &mut Economy, day: u64) {
    live_a_day_with(person, econ, day, true)
}

/// The same, but the caller says whether there is a supervisor's post
/// going.
///
/// **Advancement needs a real vacancy, not a timer.** Gated on days worked
/// alone, every labourer in a three-year run was made up to chargehand —
/// the whole cohort became supervisors, which is not a workforce. Real
/// span of control is eight to fifteen, so about one in ten of a shop or a
/// works is in charge of the rest, and the rest stay on the floor because
/// there is nowhere to go.
///
/// The person cannot see that: it is a fact about the labour market, and
/// whoever is running the labour market has to say.
pub fn live_a_day_with(
    person: &mut Person,
    econ: &mut Economy,
    day: u64,
    vacancy_above: bool,
) {
    // **What people think of you moves on the days they see you work.**
    //
    // Toward how good you actually are, but never all the way and never
    // cleanly: the read is noisy, and a fortnight's visible effort counts
    // for more than a year of quiet competence nobody witnessed. Real
    // performance ratings track real performance at about 0.3-0.5, which
    // is exactly this shape — being good helps and does not settle it.
    if person.state != State::Idle {
        // **Being seen is most of it.** A day worked in front of whoever
        // decides builds visibility; a day worked away from them does not.
        // A haulier is on the road and a shop worker is across the counter
        // from the manager, so the same ability gets noticed in one and
        // not the other.
        const HOW_FAST_YOU_GET_NOTICED: f64 = 1.0 / 200.0;
        let in_sight = match person.trade {
            Trade::Haulier => 0.25,
            _ => 1.0,
        };
        person.visibility += (in_sight - person.visibility) * HOW_FAST_YOU_GET_NOTICED;

        // Standing is the work, weighted by whether anybody watched it,
        // plus the noise that makes a rating a rating. Visibility carries
        // as much as ability, which is what the research on real promotion
        // decisions actually shows.
        const HOW_FAST_A_REPUTATION_SETTLES: f64 = 1.0 / 120.0;
        let seen = 0.45 * person.diligence
            + 0.40 * person.visibility
            + 0.15 * hash_unit(&person.name, day ^ 0x9E37_79B9);
        person.standing += (seen - person.standing) * HOW_FAST_A_REPUTATION_SETTLES;
        person.standing = person.standing.clamp(0.0, 1.0);
    }
    // A reputation fades where nobody is watching. Out of work long
    // enough and you are simply forgotten.
    if person.state == State::Idle {
        person.visibility *= 0.998;
    }

    if !person.alive() {
        return;
    }

    // --- Eat ---
    if person.larder >= 1.0 {
        person.larder -= 1.0;
        person.condition = (person.condition + 0.08).min(1.0);
        person.days_hungry = 0;
    } else {
        // Buy if there is food to be had and money to buy it with. Prices
        // are the market's, not a shop menu's, so a shortage prices a poor
        // person out before it runs the shelves bare.
        let price = econ.price(person.market, Commodity::ProcessedFood);
        let week = price * FOOD_PER_DAY * 7.0;
        if person.money >= week {
            person.money -= week;
            person.spent += week;
            person.larder += 7.0;
            person.larder -= 1.0;
            person.condition = (person.condition + 0.08).min(1.0);
            person.days_hungry = 0;
        } else if person.money >= price * FOOD_PER_DAY {
            person.money -= price * FOOD_PER_DAY;
            person.spent += price * FOOD_PER_DAY;
            person.condition = (person.condition + 0.04).min(1.0);
            person.days_hungry = 0;
        } else {
            person.days_hungry += 1;
            person.condition = (person.condition - 1.0 / DAYS_TO_STARVE).max(0.0);
            if person.days_hungry == 1 {
                person.note(day, "went hungry — could not afford a day's food");
            }
            if person.condition <= 0.0 {
                person.state = State::Dead;
                person.note(day, "died of hunger");
                return;
            }
        }
    }

    // --- Pay the rent ---
    //
    // **Due whether or not he was on the rota this week.** That is the
    // whole difficulty of it: food can be gone without for a day and rent
    // cannot be gone without at all, so a bad fortnight puts somebody out
    // of a home that a bad fortnight of hunger would not have killed.
    {
        // **Rent is a household's, not a person's**, and a household is
        // cheaper per head than living alone.
        let rent = rent_per_day(econ, person.market)
            * person.housing.share_of_rent()
            * person.household_share;

        if rent > 0.0 {
            if person.money >= rent {
                person.money -= rent;
                person.spent += rent;
            } else {
                if person.housing != Housing::Homeless {
                    person.note(day, "put out — could not find the rent");
                }
                person.housing = Housing::Homeless;
            }
        }
    }

    if person.housing == Housing::Homeless {
        person.days_homeless += 1;
        // **Sleeping out is not free either.** It costs health rather than
        // money, which is why it is a trap and not a saving: rough
        // sleeping does severe and cumulative damage, and the people it
        // happens to are the ones who could least afford to be ill.
        person.condition = (person.condition - 0.012).max(0.0);
        if person.days_homeless == 1 {
            person.note(day, "slept out");
        }
        // Back indoors as soon as there is a month's rent and a deposit,
        // which is the real barrier: the money to get in is far more than
        // the money to stay.
        let rent = rent_per_day(econ, person.market);
        let deposit = rent * 30.0 * 1.5;
        if person.money > deposit {
            person.money -= rent * 30.0 * 0.5;
            person.spent += rent * 30.0 * 0.5;
            person.housing = Housing::Lodging;
            person.days_homeless = 0;
            person.note(day, "found a room again");
        }
    }

    // --- Keep what you own ---
    //
    // **A vehicle costs money on the days it earns none.** An animal eats
    // whether it works or not and a lorry has to be housed, taxed and
    // maintained; charging upkeep only while travelling let a man own a
    // lorry for nothing on the days he was driving somebody else's.
    {
        let standing = person.conveyance.upkeep_in_wage_days(false)
            * day_rate(econ, person.market, Trade::Haulier);
        if standing > 0.0 {
            let paid = standing.min(person.money.max(0.0));
            person.money -= paid;
            person.spent += paid;
        }
    }

    // --- Work, or look for it ---
    match person.state {
        State::Working { until } if day < until => {}
        State::Working { .. } => {
            if let Some(job) = person.job.take() {
                // The work has to actually happen, or the world never
                // notices it was done. A haul that pays but moves nothing
                // leaves the price gap open, so the same job is offered
                // again tomorrow and for ever — a treadmill rather than an
                // economy.
                match job.kind {
                    // **The state pays out of tax, not out of a
                    // stockpile.** A week teaching moves no tonnage, which
                    // is exactly what a service is — and it is why a
                    // school keeps going when the mill has shut.
                    // **The goods already moved this morning.** The
                    // carrier shipped them through the journal; this is
                    // the wage for having driven, and paying it again in
                    // tonnage would be inventing freight that did not
                    // happen.
                    Job::Driving { km, .. } => {
                        person.money += job.pay;
                        person.earned += job.pay;
                        person.note(
                            day,
                            format!("drove {km:.0} km for a carrier, {:.0}", job.pay),
                        );
                    }
                    // A day's service work: it produces nothing that
                    // moves, which is what a service is.
                    Job::Service { sector, .. } => {
                        person.money += job.pay;
                        person.earned += job.pay;
                        person.note(
                            day,
                            format!(
                                "a day in {}, paid {:.0} — {:.0} in hand",
                                sector.name(),
                                job.pay,
                                person.money
                            ),
                        );
                    }
                    Job::Public { service, .. } => {
                        person.money += job.pay;
                        person.earned += job.pay;
                        person.note(
                            day,
                            format!(
                                "a week in {}, paid {:.0} — {:.0} in hand",
                                service.name(),
                                job.pay,
                                person.money
                            ),
                        );
                    }
                    Job::Haul {
                        commodity,
                        tonnes,
                        from_market,
                        to_market,
                        ..
                    } => {
                        deliver(econ, commodity, tonnes, from_market, to_market);
                        person.money += job.pay;
                        person.earned += job.pay;
                        // A driver ends up where the load was going.
                        person.market = to_market;
                        person.note(
                            day,
                            format!(
                                "delivered to {}, paid {:.0} — {:.0} in hand",
                                econ.markets[to_market].name, job.pay, person.money
                            ),
                        );
                    }
                    Job::Venture {
                        commodity,
                        tonnes,
                        from_market,
                        to_market,
                        outlay,
                        running,
                        ..
                    } => {
                        // Only what was actually carried can be sold, and
                        // only what was carried was paid for: a warehouse
                        // that has sold out since the deal was struck hands
                        // the money back rather than keeping it for goods
                        // it never loaded. Settling on the intended load
                        // instead of the delivered one paid a trader for
                        // cargo that was never there, which turned a
                        // venture into free money.
                        let carried = deliver(econ, commodity, tonnes, from_market, to_market);
                        let unfilled = 1.0 - (carried / tonnes.max(1e-9)).clamp(0.0, 1.0);
                        // The cargo comes back as money if it was never
                        // loaded. The journey does not: the fodder was
                        // eaten and the fuel was burned getting there.
                        person.money += outlay * unfilled;
                        // **Sold at whatever the market gives today**, not
                        // at the price that made the trip look worth
                        // taking. Days have passed; the price has moved.
                        // That gap is the whole risk of trading on your own
                        // account, and it can go either way.
                        let got = econ.price(to_market, commodity) * carried;
                        person.money += got;
                        let spent = outlay * (1.0 - unfilled) + running;
                        let profit = got - spent;
                        person.earned += profit;
                        person.market = to_market;
                        person.note(
                            day,
                            format!(
                                "sold {carried:.1} t of {commodity} in {} for {got:.0} \
                                 ({}{:.0} on the venture) — {:.0} in hand",
                                econ.markets[to_market].name,
                                if profit >= 0.0 { "+" } else { "" },
                                profit,
                                person.money
                            ),
                        );
                        if profit < 0.0 {
                            person.note(day, "the price had moved against him");
                        }
                    }
                    Job::Counter { .. } | Job::Shift { .. } => {
                        person.money += job.pay;
                        person.earned += job.pay;
                        person.note(
                            day,
                            format!(
                                "finished the shift, paid {:.0} — {:.0} in hand",
                                job.pay, person.money
                            ),
                        );
                    }
                }
            }
            person.state = State::Idle;
        }
        State::Idle => {
            // **A month of everything, not a month of groceries.**
            //
            // Rent is the larger of the two and is due whether or not he
            // worked, so reckoning affordability against food alone let
            // him buy a bicycle he could not keep a roof over. He was put
            // out three weeks later and stayed out for over a year,
            // because once you are on the street you are half as
            // employable and cannot save the deposit to get back in.
            let cost_of_living = econ.price(person.market, Commodity::ProcessedFood)
                * FOOD_PER_DAY
                + rent_per_day(econ, person.market) * person.housing.share_of_rent();
            let reserve_for_food = cost_of_living * 30.0;

            // --- Buy a better vehicle, if it is clearly worth it ---
            //
            // **This is the ladder.** Not a bigger purse: a bigger load.
            // A man on foot who saves for a barrow quadruples what he can
            // carry, and a man with a barrow who saves for years can buy a
            // lorry and carry a hundred and sixty times as much. The rungs
            // are far apart on purpose, because they are far apart in life.
            //
            // He buys only when he can pay for it and still keep a month's
            // food behind him, which is why the careful get there and the
            // desperate never do.
            {
                let wage = day_rate(econ, person.market, Trade::Haulier);
                let budget = (person.money - reserve_for_food * 2.0).max(0.0);
                // The ground he would actually be working. The worst road
                // out of this town, because that is the one that decides
                // whether wheels are any use.
                let surface = econ
                    .routes
                    .iter()
                    .filter(|r| r.usable() && (r.a == person.market || r.b == person.market))
                    .map(|r| r.surface)
                    .max_by_key(|s| *s as usize)
                    .unwrap_or(crate::econ::Surface::Road);
                let rate = econ
                    .routes
                    .iter()
                    .find(|r| r.a == person.market || r.b == person.market)
                    .map(|r| r.sound_cost / r.km.max(1.0))
                    .unwrap_or(0.26);
                // What a cargo costs, so a vehicle is judged on the load
                // he could actually put in it.
                let goods = econ.price(person.market, Commodity::Grain).max(1e-6);
                // How much of his life he actually spends trading on his
                // own account. A man three months into the job has no
                // record, so give him the benefit of a modest doubt.
                let seen = (person.days_worked + person.days_idle).max(1) as f64;
                let usage = if seen < 90.0 {
                    0.25
                } else {
                    (person.days_offered as f64 / seen).clamp(0.0, 1.0)
                };
                if let Some((better, price)) = Conveyance::best_upgrade(
                    person.conveyance,
                    budget,
                    wage,
                    surface,
                    rate,
                    goods,
                    usage,
                ) {
                    person.money -= price;
                    person.spent += price;
                    person.conveyance = better;
                    person.note(
                        day,
                        format!(
                            "bought {} for {price:.0} — carries {:.0} kg now, {:.0} in hand",
                            better.name(),
                            better.payload() * 1000.0,
                            person.money
                        ),
                    );
                }
            }

            let stakeable = (person.money - reserve_for_food).max(0.0);
            let offers = work_available(econ, person.market, day, stakeable, person.conveyance);
            // Take the best work this person is trained for, can afford to
            // stake, and is well enough to do. Never stake so much that a
            // bad trip leaves nothing to eat with — which is what keeps a
            // careful man alive and is also why the poor stay on wages.
            let reserve = reserve_for_food;
            // **Somebody else may get it.**
            //
            // A slack labour market does not mainly feel like low wages,
            // it feels like not being taken on. Where there are more hands
            // than posts, the work goes to one of them and not the others,
            // and which one is not a thing anybody chooses — so it is
            // drawn, deterministically, from who he is and what day it is.
            //
            // **A venture is exempt, and that matters.** Nobody hires you
            // to trade on your own account, so working for yourself is the
            // way out of a town with no work in it — which is exactly why
            // a vehicle is worth saving for.
            if offers.iter().any(|c| c.stake() > 0.0) {
                person.days_offered += 1;
            }
            if offers.iter().any(|c| c.stake() > 0.0) {
                person.days_offered += 1;
            }
            let mut hiring = econ
                .workforce
                .get(person.market)
                .map(|w| w.chance_of_work())
                .unwrap_or(1.0);
            // **A contract is a hold on the work, not a daily audition.**
            //
            // Somebody on guaranteed hours is paid on their contracted
            // days whether or not trade was brisk; that is what a contract
            // *is*, and it is what 56% of British employees have. Only
            // casual work — 2.9% of employment, and 28.8% of the
            // hospitality workforce against 2.1% of public
            // administration — is offered shift by shift.
            //
            // Modelled as what it does: a contract makes work reliably
            // available on the days it covers, and slack in the wider
            // labour market cannot take that away.
            // **A seasonal hand's year has a shape.** Work is plentiful
            // for a few weeks and thin for the rest, which is not
            // unemployment — it is the job, and it is why such a person
            // must earn hard in August to eat in February.
            if person.employment == Employment::Seasonal {
                let harvest = econ
                    .markets
                    .get(person.market)
                    .map(|m| m.harvest(day))
                    .unwrap_or(1.0);
                hiring *= person.employment.in_season(harvest);
            }
            if person.employment.is_contracted() {
                let due = person.employment.contracted_days_a_week() / 7.0;
                if draw(&person.name, day ^ 0x51_C0_17) < due {
                    // A contracted day: the work is there whatever the
                    // labour market is doing. That is what a contract is.
                    hiring = 1.0;
                }
                // **And off a contracted day they can still pick something
                // up.** A contract sets a floor on the hours, not a
                // ceiling: real practice is that a part-timer takes extra
                // shifts and about 1.2 million Britons — 3.7% — hold a
                // second job outright. Treating a day off as *forbidden*
                // work put a part-time shop worker on 2.75 days a week
                // flat, which after rent and food does not feed anybody,
                // and left nobody able to work the days needed to be
                // promoted.
            }

            // **The week, applied last.**
            //
            // A contract guarantees the days the *trade* works, not any
            // five in seven: an office keeps Monday to Friday and that is
            // what the contract is for. Applying this before the contract
            // let the guarantee overwrite it, and full-time office workers
            // came out working weekends at 0.87 times a weekday.
            //
            // A shop or a kitchen is open seven days and busiest on
            // Saturday, and the weekend shifts fall to whoever is not on a
            // full-time contract — which is why student and part-time work
            // *is* weekend work. Not a preference: it is where the shifts
            // that are going actually are.
            hiring *= works_on(person.trade, day, person.employment);

            // **A child under school age is a reason people do not work.**
            //
            // Not a metaphor — it is arithmetic a parent actually does. A
            // full-time nursery place for an under-two takes **65% of a
            // median take-home wage** in England; after-school care for a
            // five to eleven year old takes 17%. If the childcare costs
            // more than the day pays, the day is not worth working, and
            // that is why maternal employment with under-fives is **just
            // over 60% against about 75% overall**.
            //
            // It has to be applied *here*, where the work is decided.
            // Charged afterwards it could not prevent anything, and
            // parents came out working more than the childless.
            // **And how much of it the parent actually bears depends on
            // the state.** A below-replacement birth rate is only destiny
            // if nobody carries any of this: real family spending runs
            // from 0.6% of GDP in the United States to about 4% in France,
            // and Sweden caps what a parent pays at roughly 3% of income
            // against England's 65% of a wage.
            let borne = econ
                .government
                .as_ref()
                .map(|g| g.childcare_borne_by_parents())
                .unwrap_or(1.0);
            let childcare: f64 = person
                .children
                .iter()
                .map(|&age| childcare_share_of_wage(age) * borne)
                .sum();
            if childcare > 0.0 {
                // What is left of a day's pay after paying somebody to
                // mind them. At 65% for one and 130% for two, the second
                // child is what actually stops people.
                let worth_it = (1.0 - childcare).max(0.0);
                hiring *= worth_it;
            }
            // **No address, no job.** A fixed address goes on the form,
            // and not having one is one of the largest barriers there is
            // to getting off the street — which is what makes homelessness
            // self-sustaining rather than a bad month.
            if person.housing == Housing::Homeless {
                hiring *= 0.45;
            }
            let drawn = draw(&person.name, day);
            // **The only way up.** A man who has put in a couple of years
            // on the floor can be made a chargehand; a man off the street
            // cannot. Real promotion to supervisor runs two to three years
            // in, which is about where this sits.
            const YEARS_BEFORE_THEY_TRUST_YOU: u64 = 500;
            // **Not a timer.** Time on the floor is necessary and nowhere
            // near sufficient: what decides it is whether there is a post
            // going and what the people who fill it think of you.
            const WELL_ENOUGH_REGARDED: f64 = 0.62;
            let promotable = person.trade != Trade::Supervisor
                && person.days_worked >= YEARS_BEFORE_THEY_TRUST_YOU
                && vacancy_above
                && person.standing >= WELL_ENOUGH_REGARDED;
            // **Judge a job by what it pays a day, not by its total.**
            //
            // `find` took the first offer in list order, so a fourteen-day
            // haul beat a day's driving for the same daily rate purely by
            // being longer and earlier in the list — and hauls are
            // settled on what was actually delivered, so the long one
            // routinely paid a fraction of what it promised. A man came
            // out of a full year on 2.66 a day against a going rate of
            // 5.18.
            //
            // Where the daily rate ties, the shorter job wins: a week
            // committed to one load is a week of not taking anything
            // else, which is exactly why a steady job at a haulage firm
            // is worth more than a speculative cargo at the same money.
            let mut offers = offers;
            offers.sort_by(|a, b| {
                let per_day = |c: &Contract| c.pay / c.days.max(1.0);
                per_day(b)
                    .total_cmp(&per_day(a))
                    .then(a.days.total_cmp(&b.days))
            });
            let taken = offers.into_iter().find(|c| {
                let hired = c.stake() > 0.0 || drawn < hiring;
                // **You cannot take work you are not qualified for.**
                // Without this a man off the street could be an engineer,
                // and three years at a university bought nothing because
                // nothing required it.
                let allowed = person.qualification >= qualification_for(c.trade);
                let qualified = allowed
                    && (c.trade == person.trade
                        || (c.trade == Trade::Supervisor && promotable));
                qualified
                    && hired
                    && (person.condition > 0.4 || c.days <= 3.0)
                    && c.stake() <= (person.money - reserve).max(0.0)
            });
            // **A contract is something you get after they have seen
            // you.** Real practice: a probation period, then permanent —
            // typically three to six months. Which is why somebody new to
            // a town is casual first however good they are, and why losing
            // a job resets that.
            const DAYS_BEFORE_THEY_PUT_YOU_ON_THE_BOOKS: u64 = 120;
            if person.employment == Employment::None
                && person.days_worked >= DAYS_BEFORE_THEY_PUT_YOU_ON_THE_BOOKS
            {
                let (full, part, _casual) = employment_mix(person.trade);
                let r = draw(&person.name, day ^ 0xC0_47_AC_17);
                // **Some of the land work is seasonal, and that is a
                // different life.** Britain brings in ~45,000 people a
                // year purely to get the harvest in, and real agricultural
                // employment swings about twofold season to season.
                const LAND_WORK_THAT_IS_SEASONAL: f64 = 0.30;
                person.employment = if person.trade == Trade::Labourer
                    && draw(&person.name, day ^ 0x5EA_50_4A) < LAND_WORK_THAT_IS_SEASONAL
                {
                    Employment::Seasonal
                } else if r < full {
                    Employment::FullTime
                } else if r < full + part {
                    Employment::PartTime
                } else {
                    Employment::Casual
                };
                person.note(
                    day,
                    format!(
                        "put on the books {} after {} days",
                        person.employment.name(),
                        person.days_worked
                    ),
                );
            }
            if let Some(c) = taken {
                // Take the stripes and you keep them.
                if c.trade == Trade::Supervisor && person.trade != Trade::Supervisor {
                    person.note(
                        day,
                        format!(
                            "made up to chargehand after {} days on the floor",
                            person.days_worked
                        ),
                    );
                    person.trade = Trade::Supervisor;
                }
                person.days_idle = 0;
                if c.stake() > 0.0 {
                    person.days_trading += c.days.ceil() as u64;
                }
                person.money -= c.stake();
                person.note(day, format!("took work: {}", c.describe(econ)));
                person.state = State::Working {
                    until: day + c.days.ceil() as u64,
                };
                person.days_worked += c.days.ceil() as u64;
                person.job = Some(c);
            } else {
                // **When a town stops working, people leave it.**
                //
                // He sat in a place at 89% unemployment and starved over
                // six weeks with a road out of it and the fare in his
                // pocket. That is not what anybody does. Migration is the
                // oldest response to a dead local economy and leaving it
                // out made the simulation quietly cruel in a way real life
                // is not — famine happens to people who *cannot* leave.
                //
                // He goes when work here has dried up and somewhere in
                // reach is visibly better, and he has to be able to afford
                // to get there and eat when he arrives. Somebody with
                // nothing is trapped, which is the real shape of it.
                person.days_idle += 1;
                let here = econ
                    .workforce
                    .get(person.market)
                    .map(|w| w.unemployment)
                    .unwrap_or(0.0);

                // **What actually drives somebody out is the bread price,
                // not the unemployment rate.**
                //
                // Nobody sees a statistic. What a man notices is that
                // there is no work this week and a loaf costs what a day
                // used to pay — and by the time an unemployment figure has
                // worked its way through three weeks of labour stickiness,
                // he is already too poor to buy his way out. Triggering on
                // the number he cannot see trapped him in a dying town
                // with the fare still in his pocket.
                let wage = day_rate(econ, person.market, person.trade);
                let bread = econ.price(person.market, Commodity::ProcessedFood) * FOOD_PER_DAY;
                let desperate = here > 0.25 || bread * 3.0 > wage || person.days_idle > 10;
                let moved = if desperate && person.condition > 0.35 {
                    leave_town(person, econ, day)
                } else {
                    false
                };
                if !moved && (person.days_idle == 3 || person.days_idle % 21 == 0) {
                    person.note(
                        day,
                        format!(
                            "{} days without work, bread at {bread:.2} against a wage of {wage:.2}",
                            person.days_idle
                        ),
                    );
                }
            }
        }
        State::Dead => {}
    }
}

/// Try to walk to a town with work in it. Returns whether he set off.
///
/// The journey is real: it takes as long as his own legs or wheels need,
/// and he eats on the way. That is what makes it a decision rather than a
/// teleport — a man who leaves it too late cannot afford the road.
fn leave_town(person: &mut Person, econ: &Economy, day: u64) -> bool {
    let food = econ.price(person.market, Commodity::ProcessedFood) * FOOD_PER_DAY;
    let mut best: Option<(usize, f64, f64, String)> = None;

    for r in econ.routes.iter() {
        if !r.usable() || (r.a != person.market && r.b != person.market) {
            continue;
        }
        let there = if r.a == person.market { r.b } else { r.a };
        let Some(speed) = person.conveyance.km_per_day(r.surface) else {
            continue;
        };
        let days = (r.km / speed).max(1.0).ceil();
        // He must be able to eat the whole way and still land with a few
        // days in hand, or the journey kills him rather than saving him.
        let fare = food * days * 1.5 + person.conveyance.upkeep_in_wage_days(true)
            * day_rate(econ, person.market, Trade::Haulier)
            * days;
        if fare > person.money {
            continue;
        }
        let Some(w) = econ.workforce.get(there) else {
            continue;
        };
        // Worth the trip only if it is meaningfully better than here.
        // He knows what a person could know: whether that town's works are
        // running, and what they charge for bread there — the second is
        // the thing travellers have always actually carried news of.
        let gain = econ.workforce[person.market].unemployment - w.unemployment;
        let cheaper = (food - econ.price(there, Commodity::ProcessedFood) * FOOD_PER_DAY)
            / food.max(1e-9);
        if gain < 0.15 && cheaper < 0.20 {
            continue;
        }
        let score = (gain + cheaper) / days;
        if best.as_ref().is_none_or(|(_, s, _, _)| score > *s) {
            best = Some((there, score, days, econ.markets[there].name.clone()));
        }
    }

    let Some((there, _, days, name)) = best else {
        return false;
    };
    let fare = food * days * 1.5;
    person.money -= fare;
    person.spent += fare;
    person.market = there;
    person.larder = (person.larder + days * 0.5).min(7.0);
    person.state = State::Working {
        until: day + days as u64,
    };
    person.job = None;
    person.note(
        day,
        format!(
            "left for {name} — {days:.0} days on the road, {:.0} in hand",
            person.money
        ),
    );
    true
}
