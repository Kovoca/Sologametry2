/// **What a tenancy costs here, per day.**
///
/// Housing is a quarter to a third of a low income *(real: 25-35%, and
/// "housing stressed" is the term for anything over 30)*, against a tenth
/// to a seventh on food. It is the largest thing a household buys and it
/// was not modelled at all, so everybody lived rent-free and the poorest
/// person in the world could still save for a lorry.
///
/// Priced off the local wage rather than off a land market, which does
/// not exist yet: where wages are high, so is rent, which is most of what
/// a land market would tell us anyway.
pub fn rent_per_day(econ: &Economy, market: usize) -> f64 {
    const SHARE_OF_A_WAGE: f64 = 0.30;
    day_rate(econ, market, Trade::Labourer) * SHARE_OF_A_WAGE
}

/// **What somebody is qualified to do**, which the model did not ask.
///
/// Anybody could be anything: a man off the street could be an engineer,
/// and three years at a university bought nothing because nothing required
/// it. Real work is gated, and sharply — you cannot be a doctor without
/// medical school and you can be a shop worker without anything at all.
///
/// Real UK: about **35% of working-age adults hold a degree** and initial
/// participation in higher education is around 38% of young people;
/// apprenticeship starts run about 340,000 a year, down from 750,000.
#[derive(Copy, Clone, PartialEq, Eq, PartialOrd, Ord, Debug)]
pub enum Qualification {
    /// School and no more. Which is enough for most work, and always has
    /// been.
    School,
    /// **An apprenticeship or a college course** — two to four years,
    /// paid but poorly, and it is what a skilled trade actually requires.
    Vocational,
    /// **A degree** — three years not earning, and the gate on teaching,
    /// nursing, engineering, law and everything in an office.
    Degree,
}

impl Qualification {
    /// **What it takes to get through it**, on the same 0-1 scale as
    /// aptitude.
    ///
    /// Not everybody can do everything, and pretending otherwise makes a
    /// nonsense of both education and of the people who do not have it.
    /// Real: graduates average about two thirds of a standard deviation
    /// above the mean in cognitive ability, and university non-completion
    /// runs 6-7% in Britain while apprenticeship non-completion runs
    /// 30-40% — a course you cannot do is a course you leave.
    pub fn takes_to_finish(self) -> f64 {
        match self {
            Qualification::School => 0.0,
            // A trade is demanding in its own way and less academically
            // selective, which is most of why it is a different route
            // rather than a lesser one.
            Qualification::Vocational => 0.20,
            // Ability is drawn so that most people are middling: this
            // floor puts a degree out of reach for roughly the bottom
            // third, and leaves it *possible* for the rest. It is not the
            // graduate average — graduates average well above it, because
            // the odds keep rising with ability above the bar.
            Qualification::Degree => 0.42,
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Qualification::School => "school",
            Qualification::Vocational => "apprenticed",
            Qualification::Degree => "a degree",
        }
    }

    /// **Years not earning to get it.**
    ///
    /// An apprenticeship is paid, badly, so it costs less than it looks; a
    /// degree is three years of foregone earnings and fees on top. That
    /// cost is the barrier, and it is why participation tracks whether
    /// somebody's family can carry them rather than whether they are able.
    pub fn years_to_earn(self) -> f64 {
        match self {
            Qualification::School => 0.0,
            Qualification::Vocational => 3.0,
            Qualification::Degree => 3.0,
        }
    }

    /// What share of a normal wage somebody earns while training. An
    /// apprentice is paid; a student is not.
    pub fn pay_while_training(self) -> f64 {
        match self {
            Qualification::School => 1.0,
            Qualification::Vocational => 0.45,
            Qualification::Degree => 0.0,
        }
    }
}

/// **What a trade requires before anybody will have you.**
///
/// This is what makes education worth anything: without it a degree is
/// three years of not earning in exchange for nothing.
pub fn qualification_for(trade: Trade) -> Qualification {
    match trade {
        // No licence, no ticket, no training. Which is why anybody can do
        // it and why the wage knows it.
        Trade::Shopworker | Trade::Hospitality | Trade::Labourer => Qualification::School,
        // **A skilled trade is an apprenticeship**, and a lorry is a
        // licence. Both are years, and both are why the work pays more
        // than shop work does.
        Trade::Builder | Trade::Haulier => Qualification::Vocational,
        // Teaching and nursing are degree-entry, and so is everything in
        // an office worth having.
        Trade::Public | Trade::Office => Qualification::Degree,
        // **Nothing gates a chargehand.** It is promotion from the floor,
        // which is the whole point of it and the only ladder somebody
        // without a qualification can climb.
        Trade::Supervisor => Qualification::School,
    }
}

/// **When a child stops being ruinously expensive**, in years.
///
/// School. Real: compulsory education starts at five in Britain and runs
/// to sixteen, and the change in what a child costs on that birthday is
/// the sharpest financial cliff most households ever cross.
pub const SCHOOL_STARTS: f64 = 5.0;
pub const SCHOOL_ENDS: f64 = 16.0;

/// **What looking after a child costs a day**, as a share of one adult's
/// wage.
///
/// The real English figures, and they are extraordinary: **a full-time
/// nursery place for a child under two takes 65% of a median take-home
/// wage**; after-school care for a five to eleven year old takes 17%; and
/// from sixteen it is nothing but food and a roof.
///
/// The reason is staffing ratios, which are tighter in England than
/// almost anywhere in Europe — a nursery keeps one adult to three
/// under-twos. You cannot make childcare cheap without making it worse,
/// which is why it is expensive everywhere that regulates it.
pub fn childcare_share_of_wage(child_age: f64) -> f64 {
    if child_age < SCHOOL_STARTS {
        0.65
    } else if child_age < SCHOOL_ENDS {
        0.17
    } else {
        0.0
    }
}

/// **What each member of a household of this size carries**, on the
/// modified OECD equivalence scale.
///
/// First adult 1.0, each further adult 0.5, each child 0.3 — so a
/// household of `n` adults costs `1 + 0.5(n-1)` and each carries that
/// divided by `n`. One person carries 1.0, two carry 0.75 each, three
/// 0.67, four 0.625.
///
/// This is the real reason shared housing exists, and it is not small:
/// **a quarter off the cost of living** for moving in with somebody.
pub fn household_share_for(adults: usize) -> f64 {
    let n = adults.max(1) as f64;
    (1.0 + 0.5 * (n - 1.0)) / n
}

/// Wage per day for a trade, from what the work is worth and how many
/// hands are chasing it.
///
/// Labour share of output is 50-60% in reality (spec A.8), so a day's pay
/// tracks a day's production value. On top of that sits the state of the
/// local labour market: **wages sag where the works are idle**, though not
/// nearly as far as the idleness itself, because nominal wages are sticky
/// and what really gives is whether anybody is hiring at all.
pub fn day_rate(econ: &Economy, market: usize, trade: Trade) -> f64 {
    let index = econ
        .workforce
        .get(market)
        .map(|w| w.wage_index)
        .unwrap_or(1.0);
    day_rate_for_food(econ, market, trade) * index
}

fn day_rate_for_food(econ: &Economy, market: usize, trade: Trade) -> f64 {
    // Anchored to what a day's food costs, which is what a wage has to
    // cover before anything else — but to the *settled* cost, not this
    // morning's. Pay is renegotiated once a year, so it lags a price
    // shock by months, and that lag is how a shock actually makes people
    // poorer. Tying it to today's price meant bread and wages quintupled
    // together in a blackout and nobody noticed one.
    let food = econ
        .workforce
        .get(market)
        .map(|w| w.food_anchor)
        .filter(|a| *a > 0.0)
        .unwrap_or_else(|| econ.price(market, Commodity::ProcessedFood) * FOOD_PER_DAY);
    // **Real low-wage work buys six to ten days of food for a day's
    // labour**, which is the same thing as saying the poorest households
    // spend something like a tenth to a sixth of their income on eating.
    // These sat at 2.6 and 3.2 — a third of the real figure, and the note
    // recording the real one had been in the project file the whole time.
    //
    // It is not a cosmetic error. At 2.6 a labourer who gets work three
    // days in five cannot feed himself working flat out, so nobody ever
    // saved for anything and every life ended a little poorer than it
    // began. Being *at* subsistence is the historical condition; being
    // permanently below it is not, or there would be nobody left.
    let multiple = match trade {
        // Driving is entry-level freight work; a shift at a works pays a
        // little less for less risk and no lorry.
        Trade::Haulier => 7.0,
        Trade::Labourer => 6.0,
        // Shop work is the worst-paid of the three and always has been:
        // it needs no licence, no ticket and no strength, so anybody can
        // do it and the wage knows it. **But it is still a wage**, and
        // this file already records the band: real low-wage work buys 6-10
        // days of food. At 5.0 a shop worker who got 35% of the days —
        // which is what part-time retail on a weekend rota actually is —
        // could not keep a roof, and that is not the historical condition
        // of shop work, it is destitution.
        Trade::Shopworker => 6.0,
        // A chargehand is paid a third again over the people watched,
        // which is about the real premium and about what makes it worth
        // the aggravation.
        Trade::Supervisor => 8.5,
        // **The public sector pays a little better at the bottom and
        // rather worse at the top**, which is the real and well-measured
        // shape of it: a cleaner or a clerk does better in the public
        // sector than out of it, a senior professional does considerably
        // worse. Averaged across teaching, nursing, clerking and policing
        // it sits a shade above a labourer — and it comes with something
        // the private jobs here do not have, which is that the work is
        // steady.
        Trade::Public => 6.5,
        // Construction pays a shade above the average — UK median £35k
        // against £33k for all employees — and more for a skilled trade.
        Trade::Builder => 7.0,
        // **The worst-paid sector there is.** Around £20k against a £33k
        // median, and the hours are not guaranteed either — so it sits at
        // the very bottom of the 6-10 band rather than below it.
        Trade::Hospitality => 5.5,
        // Professional, technical and financial work is the best paid,
        // and it is why people move to cities for it.
        Trade::Office => 9.5,
    };
    food * multiple
}

/// Every piece of work on offer in `market` today.
///
/// Generated from the economy's own state, never for anybody's benefit: a
/// haul exists when moving goods along a route is worth more than the
/// freight, and a shift exists when a works has the inputs to run and
/// somewhere to put the output. If the arithmetic does not say so, there
/// is no work, and a person who needs work is simply out of luck.
/// Work on offer in `market`, for somebody with `purse` to stake.
///
/// The purse matters because a venture is only on offer to a person who
/// can buy the load. That is not the world adapting to the player — the
/// cargo costs what it costs — it is the plain fact that you cannot trade
/// on your own account with empty pockets. A man with nothing sees only
/// wages, which is the point.
pub fn work_available(
    econ: &Economy,
    market: usize,
    day: u64,
    purse: f64,
    conveyance: Conveyance,
) -> Vec<Contract> {
    let mut out = Vec::new();

    // Hauls: the arbitrage the trade system is already finding, offered as
    // a job rather than executed invisibly.
    for r in 0..econ.routes.len() {
        let route = &econ.routes[r];
        if !route.usable() || (route.a != market && route.b != market) {
            continue;
        }
        let surface = route.surface;
        for &c in Commodity::ALL.iter() {
            if !c.storable() {
                continue;
            }
            let margin = econ.arbitrage(r, c);
            if margin <= 0.0 {
                continue;
            }
            let (from, to) = if econ.price(route.b, c) > econ.price(route.a, c) {
                (route.a, route.b)
            } else {
                (route.b, route.a)
            };
            // A wage haul is driving the firm's lorry, so it moves a
            // lorry-load and travels at a lorry's speed whatever the driver
            // personally owns. The rest of the arbitrage is somebody
            // else's to take — and only out of what the sending town will
            // actually part with, or the job is a wage for driving an
            // empty lorry over a hill.
            let tonnes = Conveyance::Artic
                .payload()
                .min(route.capacity * 0.02)
                .min(econ.surplus(from, c))
                .max(0.0);
            if tonnes < 0.2 {
                continue;
            }
            let Some(speed) = Conveyance::Artic.km_per_day(surface) else {
                continue; // no lorry gets over this
            };
            let days = (route.km / speed).clamp(1.0, 60.0);

            // **The driver is paid a wage, not the margin.**
            //
            // The margin belongs to whoever owns the cargo, and a driver
            // does not. Paying it to the haulier made one load worth two
            // years of a man's food and turned the job into a money
            // printer — which is not a bug in the arithmetic so much as a
            // misunderstanding of who is being paid for what. Somebody who
            // wants the margin has to buy the goods first and carry the
            // risk of the price moving under them, which is the trader's
            // path and a different, later thing.
            //
            // A haul on a route the merchant is making good money on pays
            // a little over the going rate, because he can afford it and
            // wants it done today.
            let rate = day_rate(econ, market, Trade::Haulier);
            let keenness = (1.0 + margin / c.base_cost()).clamp(1.0, 1.6);
            out.push(Contract {
                kind: Job::Haul {
                    route: r,
                    commodity: c,
                    tonnes,
                    from_market: from,
                    to_market: to,
                },
                posted: day,
                // Work goes to whoever is there. A haul nobody takes
                // within a week has been taken by somebody else.
                expires: day + 7,
                pay: rate * days * keenness,
                days,
                trade: Trade::Haulier,
            });

            // The same journey on your own account. The margin is yours
            // instead of the wage — and so is the risk of the price having
            // moved by the time you arrive.
            //
            // **Two things bind, and both are real.** The purse says what
            // you can buy. The vehicle says what you can carry, and it is
            // usually the binding one: a man on foot takes 35 kg over the
            // pass however rich he is, and 35 kg of grain will not make
            // anybody's fortune. That is why the ladder out is a handcart
            // and then a mule and then a lorry, and why most people never
            // get past the first rung.
            //
            // You can also only buy what is actually for sale. A market
            // quotes a price for everything, including things it has none
            // of and things it is holding back, and offering a venture
            // against either stakes money on a cargo never loaded.
            let for_sale = econ.surplus(from, c);
            let Some(own_speed) = conveyance.km_per_day(surface) else {
                continue; // he cannot get there with what he has
            };
            let own_days = (route.km / own_speed).clamp(1.0, 120.0);

            let unit = econ.price(from, c).max(1e-6);
            let affordable = (purse / unit)
                .min(conveyance.payload())
                .min(for_sale);
            // Getting there costs something even before the cargo: fodder
            // for an animal that eats whether it earns or not, diesel for
            // a lorry that costs several times its driver's wage to run.
            let wage = day_rate(econ, market, Trade::Haulier);
            let running = conveyance.upkeep_in_wage_days(true) * wage * own_days;
            if affordable >= 0.005 {
                let outlay = unit * affordable;
                let days = own_days;
                out.push(Contract {
                    kind: Job::Venture {
                        route: r,
                        commodity: c,
                        tonnes: affordable,
                        from_market: from,
                        to_market: to,
                        outlay,
                        running,
                    },
                    posted: day,
                    expires: day + 7,
                    // **What he clears, not what the load fetches.**
                    //
                    // This advertised the gross sale price with neither
                    // the cost of the cargo nor the diesel taken off —
                    // turnover offered as though it were income. Against a
                    // wage it looked like three times the going rate, so
                    // once offers were ranked by what they pay a day a
                    // haulier took a venture every time and came out of a
                    // full year on 2.66 a day against a rate of 5.18.
                    //
                    // Expected, not guaranteed: what it fetches is
                    // whatever the far market will pay on the day it
                    // arrives, and the cargo may be gone before he gets
                    // there — which is what makes it a risk and not a
                    // better wage.
                    pay: (econ.price(to, c) * affordable - outlay - running).max(0.0),
                    days,
                    trade: Trade::Haulier,
                });
            }
        }
    }

    // Routine haulage: the ordinary freight of the country.
    //
    // Arbitrage is the interesting kind of haul and almost none of the real
    // kind. Most of what a lorry does is move a firm's own stock to where
    // the firm wants it, with no price gap involved at all — and offering
    // only the arbitrage hauls left a driver in a city of sixteen million
    // with nothing to do for four months, which starved him. The work
    // exists because the freight exists.
    //
    // It still is not a gift: it pays the going rate and no more, and it
    // only appears where a town genuinely has a surplus of something and
    // its neighbour has room for it.
    for r in 0..econ.routes.len() {
        let route = &econ.routes[r];
        if !route.usable() || (route.a != market && route.b != market) {
            continue;
        }
        // **The cargo is whatever the economy actually shipped today.**
        //
        // Not something chosen from inventory: firms move their own stock
        // for their own reasons, and a driver is hired to drive it. Making
        // up loads from the biggest surplus had him shuttling the same
        // grain between the same two towns for a decade, out on Monday and
        // back on Tuesday, paid both ways and nobody any better off.
        let Some((c, to, shipped)) = route.moved else {
            continue;
        };
        if to == market {
            continue; // today's freight is coming *here*, not going
        }
        let other = to;
        let days = (route.freight_cost / 40.0).clamp(1.0, 14.0);
        let rate = day_rate(econ, market, Trade::Haulier);
        let tonnes = shipped.min(Conveyance::Artic.payload());
        if tonnes < 0.2 {
            continue;
        }

        out.push(Contract {
            kind: Job::Haul {
                route: r,
                commodity: c,
                tonnes,
                from_market: market,
                to_market: other,
            },
            posted: day,
            expires: day + 7,
            pay: rate * days,
            days,
            trade: Trade::Haulier,
        });
    }

    // **Driving for a carrier.**
    //
    // Founding a freight industry and leaving the drivers out of it was
    // an odd sort of omission: the carriers shifted four thousand tonnes
    // a day and employed nobody, while the one man with a lorry watched
    // the price gaps he used to live on close up behind them. That second
    // part is real — a competitive haulage industry does compete away the
    // arbitrage a lone trader was making — but it has to come with the
    // wages it pays, or the model has taken his living and given nothing
    // back.
    //
    // Real transport and storage is **5.0% of employment**, and almost
    // none of it is self-employed arbitrage.
    if let Some(freight) = econ.logistics.as_ref() {
        // **A carrier with nothing to move is not hiring.** Offering a
        // day's driving purely because a firm owns lorries kept a man
        // employed in an economy whose roads were shut and whose works
        // had all stopped — which is the one situation the model must get
        // right, because destitution is what the person layer exists to
        // be able to show.
        //
        // Gated on the industry rather than the individual firm: a
        // haulier does not lay off his drivers because Tuesday was quiet,
        // which is the labour-hoarding rule this project already follows
        // everywhere else.
        let anything_moving = freight.hauled_today() > 0.0;
        for (i, carrier) in freight.carriers.iter().enumerate() {
            if !anything_moving {
                break;
            }
            if carrier.home != market || carrier.drivers() < 1.0 {
                continue;
            }
            // **Not gated on how busy the trunk fleet looks.**
            //
            // The fleet is sized on the town's whole freight task — the
            // real 24 tonnes a head a year — while `haul` only does the
            // long-distance balancing, because collection and delivery
            // inside a town are handled abstractly by `distribute` and
            // never put a lorry on the road. So measured utilisation runs
            // at a few percent and means nothing, and gating hiring on it
            // put a driver out of work in a town whose carrier ran seven
            // hundred vehicles — on a threshold of five percent against a
            // reading of 4.9.
            //
            // A carrier employs drivers because it has a fleet. Whether
            // he gets a shift is the labour market's business, and
            // `chance_of_work` already decides that.
            let rate = day_rate(econ, market, Trade::Haulier);
            out.push(Contract {
                kind: Job::Driving {
                    carrier: i,
                    km: freight.mean_haul_km(),
                },
                posted: day,
                expires: day + 1,
                pay: rate,
                days: 1.0,
                trade: Trade::Haulier,
            });
        }
    }

    // **Carting about the town.**
    //
    // Most freight is local and always was: grain from the farm to the
    // mill, flour from the mill to the cannery, tins from the cannery to
    // the shops. It is short, dull, and it is the bulk of what a lorry
    // actually does — a country moves several times more tonnage inside
    // its towns than between them.
    //
    // Leaving it out was why a haulier in a city of sixteen million could
    // find seventeen days of work in three years. Inter-town freight is
    // genuinely rare here, because every town in this economy has its own
    // farm and mill and cannery and so has little need of its neighbours —
    // which is a real gap in `region.rs`, not something to paper over with
    // invented long-distance loads.
    let working_town = econ
        .ledger
        .sites
        .iter()
        .any(|s| s.market == market && s.ran > 0.0);
    if working_town {
        let rate = day_rate(econ, market, Trade::Haulier);
        out.push(Contract {
            kind: Job::Shift {
                site: usize::MAX,
                market,
            },
            posted: day,
            expires: day + 1,
            pay: rate,
            days: 1.0,
            trade: Trade::Haulier,
        });
    }

    // **Shop work.** Every fixture that needs somebody on it is a job,
    // and a shop with nothing on its shelves has none of them.
    for s in 0..econ.ledger.sites.len() {
        let site = &econ.ledger.sites[s];
        if site.market != market {
            continue;
        }
        let Some(b) = &site.fitted else { continue };
        let stocked = Commodity::ALL.iter().any(|&c| site.stock[c as usize] > 0.0);
        if !stocked {
            continue;
        }
        let rate = day_rate(econ, market, Trade::Shopworker);
        for &(role, count) in b.fixtures.iter() {
            if count * role.staff() < 1.0 {
                continue;
            }
            // **One shift, not a week.** A shop worker is put on the rota
            // a day at a time, which is the whole shape of the job: the
            // work is steady and the hours are not, and next week is
            // somebody else's decision.
            out.push(Contract {
                kind: Job::Counter {
                    site: s,
                    market,
                    role,
                },
                posted: day,
                expires: day + 1,
                pay: rate,
                days: 1.0,
                trade: Trade::Shopworker,
            });
        }
    }

    // **Public service.** The state is an employer, and in a developed
    // economy the largest single one there is: real government employment
    // is 14-21% of the workforce. A model of farms, mills and shops left a
    // sixth of everybody with nowhere to go.
    //
    // Two things separate it from the work above. **It is steady** — a
    // school does not send half the staff home because trade was slow, so
    // these are posted in weeks rather than days. And **it does not stop
    // in a blackout**: a hospital and a police station keep working when
    // the mill has shut, which is exactly why they are the services a
    // state insists on funding.
    if let Some(gov) = econ.government.as_ref() {
        let posts = gov.posts_in(market);
        if posts >= 1.0 {
            let rate = day_rate(econ, market, Trade::Public);
            // One offer per service that is actually staffed here, so a
            // town with a hospital and a school has both going.
            for service in crate::state::Service::ALL {
                if gov.posts_for(econ, market, service) < 1.0 {
                    continue;
                }
                out.push(Contract {
                    kind: Job::Public { market, service },
                    posted: day,
                    expires: day + 7,
                    // A week at a time: paid on completion like everything
                    // else here, so the sum is seven days' rate.
                    pay: rate * 7.0,
                    days: 7.0,
                    trade: Trade::Public,
                });
            }
        }
    }

    // **The private services.** Construction, hospitality, recreation and
    // offices — about 43% of all employment, and the sectors that decide
    // what a place is like to live in rather than merely to eat in:
    // somebody has to fix things, and somewhere has to be open in the
    // evening.
    if let Some(svc) = econ.services.as_ref() {
        for sector in crate::services::Sector::ALL {
            if svc.posts_in(market, sector) < 1.0 {
                continue;
            }
            let trade = sector.trade();
            let rate = day_rate(econ, market, trade);
            out.push(Contract {
                kind: Job::Service { market, sector },
                posted: day,
                expires: day + 1,
                pay: rate,
                days: 1.0,
                trade,
            });
        }
    }

    // **Supervising.** There is one of these for every ten on the floor,
    // and they exist wherever the floor is big enough to need watching.
    //
    // It is the only promotion in the economy, and it is gated the way
    // promotions are: you have to have done the job. A man off the street
    // is not made a chargehand.
    for s in 0..econ.ledger.sites.len() {
        let site = &econ.ledger.sites[s];
        if site.market != market {
            continue;
        }
        let posts = match &site.fitted {
            Some(b) => b.supervisors() + b.managers(),
            None => {
                if site.ran <= 0.0 {
                    continue;
                }
                // A works of any size has chargehands over the shifts.
                (site.throughput / 500.0).ceil().min(20.0)
            }
        };
        if posts < 1.0 {
            continue;
        }
        out.push(Contract {
            kind: Job::Shift { site: s, market },
            posted: day,
            expires: day + 3,
            pay: day_rate(econ, market, Trade::Supervisor) * 6.0,
            days: 6.0,
            trade: Trade::Supervisor,
        });
    }

    // Shifts: a works that **is running** wants hands.
    //
    // Not one that merely has power. A mill with no grain employs nobody
    // today, and a works standing idle is precisely where the jobs are
    // not — which is the whole reason the workforce is modelled.
    for s in 0..econ.ledger.sites.len() {
        let site = &econ.ledger.sites[s];
        if site.market != market || site.recipe.is_none() {
            continue;
        }
        // **A farm is not the grid's to shut, and neither are its jobs.**
        //
        // Two gates said otherwise and both were wrong the same way. A
        // works with no power offers no shifts, true — but a farm does not
        // stop for a blackout (spec A.2: its dependency is water), and it
        // has hands on it all year whether or not anything is being cut.
        // Between them these left a farm labourer with no work for months
        // when in fact there was plenty, and made a grid fault look like a
        // famine by a route that does not exist.
        let is_farm = site.kind == crate::econ::SiteKind::Farm;
        if !is_farm && (!site.powered || site.ran <= 0.0) {
            continue;
        }
        out.push(Contract {
            kind: Job::Shift { site: s, market },
            posted: day,
            expires: day + 3,
            pay: day_rate(econ, market, Trade::Labourer) * 6.0,
            days: 6.0,
            trade: Trade::Labourer,
        });
    }

    out.sort_by(|a, b| b.daily_rate().total_cmp(&a.daily_rate()));
    out
}

/// A number in 0..1 from who somebody is and what day it is.
///
/// Deterministic, because a seed has to rebuild the same world and the
/// same life forever. This is not luck in the sense of a dice roll the
/// player can reload away from — it is the part of getting hired that
/// nobody controls, and it has to be reproducible like everything else.
fn draw(name: &str, day: u64) -> f64 {
    let mut h = day.wrapping_mul(0x9E37_79B9_7F4A_7C15);
    for b in name.as_bytes() {
        h ^= *b as u64;
        h = h.wrapping_mul(0x1000_0000_01B3);
    }
    h ^= h >> 29;
    h = h.wrapping_mul(0xBF58_476D_1CE4_E5B9);
    h ^= h >> 32;
    (h >> 11) as f64 / (1u64 << 53) as f64
}

/// Move a load that a person actually carried.
///
/// Goes through the journal like every other change, so a lorry-load Hal
/// drove is the same tonnes arriving as left, and the conservation check
/// covers his work as it covers everything else.
/// Returns the tonnage that actually moved, which may be less than was
/// wanted and may be nothing at all.
///
/// Settling on the intended load rather than the delivered one pays a
/// trader for goods that were never there: a market with no stock of
/// something still quotes a price for it, and buying from an empty
/// warehouse turned a venture into free money.
fn deliver(
    econ: &mut Economy,
    commodity: Commodity,
    tonnes: f64,
    from_market: usize,
    to_market: usize,
) -> f64 {
    use crate::econ::Event;

    // Take it from whoever in the sending market has most of it, and give
    // it to whoever in the receiving market has room.
    let pick = |econ: &Economy, market: usize, most: bool| -> Option<usize> {
        (0..econ.ledger.sites.len())
            .filter(|&s| {
                econ.ledger.sites[s].market == market
                    && econ.ledger.sites[s].capacity[commodity as usize] > 0.0
            })
            .max_by(|&a, &b| {
                let score = |s: usize| {
                    if most {
                        econ.ledger.stock(s, commodity)
                    } else {
                        econ.ledger.sites[s].capacity[commodity as usize]
                            - econ.ledger.stock(s, commodity)
                    }
                };
                score(a).total_cmp(&score(b)).then(b.cmp(&a))
            })
    };

    let (Some(src), Some(dst)) = (pick(econ, from_market, true), pick(econ, to_market, false))
    else {
        return 0.0;
    };
    let room = (econ.ledger.sites[dst].capacity[commodity as usize]
        - econ.ledger.stock(dst, commodity))
    .max(0.0);
    // Nobody sells a town's working reserve at the going rate, and that
    // holds for a man with a lorry as much as for a firm. Without it the
    // most profitable trade in the country is always to strip whichever
    // town is shortest of what it is shortest of.
    let qty = tonnes
        .min(econ.ledger.stock(src, commodity))
        .min(econ.surplus(from_market, commodity))
        .min(room);
    if qty <= 1e-9 {
        return 0.0;
    }
    let mut journal = std::mem::take(&mut econ.journal);
    econ.ledger.apply(
        &mut journal,
        Event::Shipped {
            from: src,
            to: dst,
            commodity,
            qty,
        },
    );
    econ.journal = journal;
    qty
}

