//! A person living in the economy.
//!
//! The first human being in the simulation. Everything until now has been
//! a world — terrain, nations, markets, freight — with populations as
//! numbers. This is one individual inside it, with money, hunger, a skill
//! and somewhere to be.
//!
//! Three rules from the design carry the whole thing, and they are what
//! make this a person in a world rather than a character in a game:
//!
//! - **Nothing is pushed** (spec A4.1). Work exists as a fact in the
//!   world — a haul somebody needs doing — and is found by being in the
//!   right market to hear of it. No quest markers, because there are no
//!   quests.
//! - **Nothing scales to the player.** Contracts are generated by the
//!   economy's own arithmetic, not by what this person can handle. Most
//!   are out of reach, already taken, or not worth the trip.
//! - **The world does not wait.** A contract heard of last week is gone.
//!
//! What a person does *not* have yet: a body, a position finer than which
//! market they are in, relationships, beliefs, or a life beyond earning
//! and eating. Those are specced (A3, B1, B6) and unbuilt.

use crate::building::Fixture;
use crate::econ::{Commodity, Economy};
